const { chromium, browserOptions } = require('./browser.cjs');
const assert = require('assert/strict');
const fs = require('fs');
const path = require('path');
const base = process.env.PORTFOLIO_BASE_URL || 'http://127.0.0.1:3000';
const output = process.env.PORTFOLIO_EVIDENCE_DIR || __dirname;

(async () => {
 const browser = await chromium.launch(browserOptions);
 const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'no-preference' });
 context.setDefaultTimeout(10000);
 const page = await context.newPage();
 const errors=[], checks=[], sizing=[];
 const pass = label => { checks.push(label); console.log('PASS '+label); };
 const openGuide = () => page.getByRole('button',{name:'Open Byte site guide',exact:true}).click();
 const guide = page.getByRole('dialog',{name:'A little help finding your way?',exact:true});
 page.on('pageerror',error=>errors.push(error.message));
 page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
 await page.goto(base+'/about',{waitUntil:'networkidle'});
 await page.locator('[data-site-guide] img').waitFor({state:'visible'});
 assert.ok(await page.locator('[data-site-guide] img').evaluate(img=>img.complete&&img.naturalWidth>0));
 await openGuide();await guide.waitFor({state:'visible'});
 assert.equal(await page.getByRole('button',{name:'Open Byte site guide',includeHidden:true}).getAttribute('aria-expanded'),'true');
 assert.equal(await guide.getByRole('navigation',{name:'Guide shortcuts'}).getByRole('link').count(),3);
 await page.getByRole('button',{name:'Pause motion',exact:true}).click();
 assert.equal(await page.getByRole('button',{name:'Resume motion',exact:true}).getAttribute('aria-pressed'),'true');
 for(let i=0;i<10;i++){await page.keyboard.press('Tab');assert.ok(await page.evaluate(()=>!!document.activeElement.closest('#site-guide-dialog')||document.activeElement===document.body));}
 await page.keyboard.press('Escape');
 assert.equal(await guide.isVisible(),false);
 assert.equal(await page.getByRole('button',{name:'Open Byte site guide'}).evaluate(el=>el===document.activeElement),true);
 pass('Sprite, useful shortcuts, pause control, dialog focus, and Escape');
 await openGuide();await guide.getByRole('button',{name:'Hide companion',exact:true}).click();
 const restore=page.getByRole('button',{name:'Show site guide',exact:true});
 await restore.waitFor({state:'visible'});assert.equal(await restore.evaluate(el=>el===document.activeElement),true);
 assert.equal(await page.getByRole('button',{name:'Open Byte site guide'}).count(),0);
 await page.reload({waitUntil:'networkidle'});await restore.waitFor({state:'visible'});
 await restore.click();assert.equal(await page.getByRole('button',{name:'Open Byte site guide'}).evaluate(el=>el===document.activeElement),true);
 await openGuide();assert.equal(await guide.getByRole('button',{name:'Resume motion',exact:true}).getAttribute('aria-pressed'),'true');
 await guide.getByRole('button',{name:'Resume motion',exact:true}).click();
 await guide.getByRole('link',{name:'Work',exact:true}).click();await page.waitForURL('**/#work');
 await page.locator('main > div[aria-hidden="true"] bdi').waitFor({state:'detached',timeout:10000});
 assert.equal(await page.locator('dialog[open]').count(),0);assert.equal(await page.locator('[data-site-guide]').count(),1);
 pass('Hide and restore with focus, persisted preferences, and Work shortcut');
 await openGuide();await guide.getByRole('link',{name:'About',exact:true}).click();await page.waitForURL('**/about');
 assert.equal(await guide.isVisible(),false);
 await openGuide();await guide.getByRole('link',{name:'Contact',exact:true}).click();await page.waitForURL('**/#contact');
 await page.locator('main > div[aria-hidden="true"] bdi').waitFor({state:'detached',timeout:10000});
 assert.equal(await guide.isVisible(),false);
 pass('About and Contact shortcuts work across pages without leaving the guide open');
 fs.mkdirSync(output,{recursive:true});
 for(const width of [320,390,768,1024,1440]){
  await page.setViewportSize({width,height:width<768?844:1000});
  await page.goto(base+'/about',{waitUntil:'networkidle'});
  const dock=await page.locator('[data-site-guide]').boundingBox();
  const viewport=page.viewportSize();assert.ok(dock.x>=0&&dock.y>=0&&dock.x+dock.width<=width&&dock.y+dock.height<=viewport.height);
  await openGuide();const box=await guide.boundingBox();assert.ok(box.x>=0&&box.y>=0&&box.x+box.width<=width&&box.y+box.height<=viewport.height);
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  sizing.push({width,dock,panel:box});
  if(width===390||width===1440)await page.screenshot({path:path.join(output,'guide-open-'+width+'.png')});
  await page.keyboard.press('Escape');
  await page.locator('#contact').scrollIntoViewIfNeeded();
  await page.getByRole('navigation',{name:'Social links'}).scrollIntoViewIfNeeded();
  const blocked=await page.getByRole('navigation',{name:'Social links'}).getByRole('link').evaluateAll(links=>links.filter(a=>{const r=a.getBoundingClientRect();const at=document.elementFromPoint(r.x+r.width/2,r.y+r.height/2);return at&&!a.contains(at);}).map(a=>a.textContent));
  assert.deepEqual(blocked,[],'Guide covers footer links at '+width);
 }
 pass('Dock, panel, overflow, and footer hit targets at five widths');
 await page.emulateMedia({reducedMotion:'reduce'});await page.goto(base+'/about',{waitUntil:'networkidle'});
 assert.equal(await page.locator('[data-site-guide]').getAttribute('data-motion-paused'),'true');
 assert.equal(await page.locator('[data-site-guide]').evaluate(el=>el.getAnimations({subtree:true}).filter(a=>a.playState==='running').length),0);
 await openGuide();assert.ok(await guide.getByText('Motion off',{exact:true}).isVisible());await page.keyboard.press('Escape');
 await page.emulateMedia({reducedMotion:'reduce',forcedColors:'active'});await openGuide();assert.ok(await guide.getByRole('link',{name:'About',exact:true}).isVisible());
 pass('Reduced motion and forced-colors controls');
 const blockedStorage=await browser.newContext({reducedMotion:'reduce'});
 await blockedStorage.addInitScript(()=>{Storage.prototype.setItem=()=>{throw new Error('Storage disabled');};Storage.prototype.getItem=()=>{throw new Error('Storage disabled');};});
 const fallback=await blockedStorage.newPage();const fallbackErrors=[];fallback.on('pageerror',error=>fallbackErrors.push(error.message));
 await fallback.goto(base+'/about',{waitUntil:'networkidle'});await fallback.getByRole('button',{name:'Hide site guide',exact:true}).click();await fallback.getByRole('button',{name:'Show site guide',exact:true}).click();
 assert.deepEqual(fallbackErrors,[]);await blockedStorage.close();pass('Guide remains usable when browser storage is disabled');
 assert.deepEqual(errors,[]);
 fs.writeFileSync(path.join(output,'guide-verification.json'),JSON.stringify({base,browser:process.env.PORTFOLIO_BROWSER_CHANNEL||'chromium',checks,sizing,errors},null,2));
 await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
